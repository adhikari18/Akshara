#!/usr/bin/env node
/**
 * Generates src/strokes.generated.ts from stroke-manifest.json and the strokes/ directory, so
 * adding a letter or numeral means: drop the JSON in strokes/, list its id in the manifest
 * (`order` for letters, `numerals` for digits), run this script. No hand-maintained import
 * list, record, or array.
 *
 *   node scripts/generate-stroke-index.mjs          write the file
 *   node scripts/generate-stroke-index.mjs --check  fail if the committed file is stale (CI)
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = join(root, 'stroke-manifest.json');
const strokesDir = join(root, 'strokes');
const outPath = join(root, 'src', 'strokes.generated.ts');

/**
 * Validate the manifest against the strokes/ directory. Returns the ordered letter ids
 * (`order`) and numeral ids (`numerals`); every stroke file must appear in exactly one list.
 */
export function resolveStrokeManifest(paths = { manifestPath, strokesDir }) {
  const manifest = JSON.parse(readFileSync(paths.manifestPath, 'utf8'));
  const order = Array.isArray(manifest.order) ? manifest.order : [];
  const numerals = Array.isArray(manifest.numerals) ? manifest.numerals : [];
  const errors = [];
  if (order.length === 0) errors.push('manifest "order" must be a non-empty array');
  if (manifest.numerals !== undefined && !Array.isArray(manifest.numerals)) {
    errors.push('manifest "numerals" must be an array');
  }

  const files = new Set(
    readdirSync(paths.strokesDir)
      .filter((f) => f.endsWith('.json'))
      .map((f) => f.slice(0, -'.json'.length))
  );
  const seen = new Set();
  for (const id of [...order, ...numerals]) {
    if (typeof id !== 'string' || !/^[a-z][a-z0-9_-]*$/.test(id))
      errors.push(`invalid id ${JSON.stringify(id)}`);
    else if (seen.has(id)) errors.push(`"${id}" is listed twice`);
    else if (!files.has(id)) errors.push(`"${id}" is listed but strokes/${id}.json does not exist`);
    else {
      const declared = JSON.parse(readFileSync(join(paths.strokesDir, `${id}.json`), 'utf8')).id;
      if (declared !== id)
        errors.push(`strokes/${id}.json declares id "${declared}" (must match its filename)`);
    }
    seen.add(id);
  }
  for (const id of files) {
    if (!seen.has(id))
      errors.push(`strokes/${id}.json exists but is not listed in stroke-manifest.json`);
  }
  if (errors.length) {
    throw new Error(
      `stroke-manifest.json is out of sync with strokes/:\n  - ${errors.join('\n  - ')}`
    );
  }
  return { order, numerals };
}

/** Ordered letter ids only. */
export function resolveStrokeOrder(paths) {
  return resolveStrokeManifest(paths).order;
}

const identifier = (id) => `stroke_${id.replace(/[^a-zA-Z0-9]/g, '_')}`;

export function renderStrokeIndex(order, numerals = []) {
  return [
    '// AUTO-GENERATED by scripts/generate-stroke-index.mjs from stroke-manifest.json.',
    '// Do not edit by hand: add the JSON to strokes/, list its id in the manifest, then run',
    '// `npm run generate --workspace=@akshara/data`.',
    "import type { LetterStrokeDataset } from './index.js';",
    '',
    ...[...order, ...numerals].map(
      (id) => `import ${identifier(id)} from '../strokes/${id}.json' with { type: 'json' };`
    ),
    '',
    '/** Letter dataset ids in teaching order (from stroke-manifest.json). */',
    'export const STROKE_ORDER: readonly string[] = [',
    ...order.map((id) => `  '${id}',`),
    '];',
    '',
    '/** Every bundled letter dataset, keyed by id. */',
    'export const STROKE_DATASETS: Record<string, LetterStrokeDataset> = {',
    ...order.map((id) => `  '${id}': ${identifier(id)} as LetterStrokeDataset,`),
    '};',
    '',
    '/** Every bundled letter dataset, in teaching order. */',
    'export const STROKE_LIST: LetterStrokeDataset[] = STROKE_ORDER.map((id) => STROKE_DATASETS[id]!);',
    '',
    '/** Devanagari numeral ids (० – ९) in digit order, kept apart from the letter deck. */',
    'export const NUMERAL_ORDER: readonly string[] = [',
    ...numerals.map((id) => `  '${id}',`),
    '];',
    '',
    '/** Every bundled numeral dataset, keyed by id (e.g. `num-4`). */',
    'export const NUMERAL_DATASETS: Record<string, LetterStrokeDataset> = {',
    ...numerals.map((id) => `  '${id}': ${identifier(id)} as LetterStrokeDataset,`),
    '};',
    '',
    '/** Every bundled numeral dataset, in digit order (index = digit value). */',
    'export const NUMERAL_LIST: LetterStrokeDataset[] = NUMERAL_ORDER.map((id) => NUMERAL_DATASETS[id]!);',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const { order, numerals } = resolveStrokeManifest();
    const content = renderStrokeIndex(order, numerals);
    if (process.argv.includes('--check')) {
      const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
      if (current !== content) {
        console.error(
          '✗ src/strokes.generated.ts is stale. Run `npm run generate --workspace=@akshara/data`.'
        );
        process.exit(1);
      }
      console.log('✓ src/strokes.generated.ts is up to date.');
    } else {
      writeFileSync(outPath, content);
      console.log(
        `✓ Wrote src/strokes.generated.ts (${order.length} letters, ${numerals.length} numerals).`
      );
    }
  } catch (err) {
    console.error(`✗ ${err.message}`);
    process.exit(1);
  }
}
